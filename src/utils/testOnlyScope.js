/**
 * משתמשי "פעיל לטסטים" (User.testOnly) גלויים רק למנהל-העל.
 * כל שליפת משתמשים לרשימות/טפסים ממזגת את הפילטר הזה. הבדיקה לפי המשתמש
 * האפקטיבי (req.user) - כך שגם ב"צפייה בתור" הרשימה משקפת את מה שהמשתמש
 * המוצג היה רואה בעצמו.
 */
export const excludeTestOnly = (req) =>
  req?.user?.superAdmin === true ? {} : { testOnly: { $ne: true } };
